import { bundleFrom } from '../../src/connector-source.ts';
import { hashManifest } from '../../src/hash.ts';
import { credentialFields, type Manifest } from '../../src/manifest.ts';
import { applyDecisions, connectorSettings, envName, isAllowed, type Decisions } from './decisions.ts';
import type { AppPack } from './pack.ts';

export type BundleFile = { name: string; code: string };
export const FOLDER = (m: Manifest) => `src/integrations/${m.app.slug}/`;

const usageLine = (m: Manifest) => (m.usage.kind === 'unavailable' ? `not included. ${m.usage.reason}` : m.usage.kind === 'last_activity_field' ? 'last activity from the user record' : `${m.usage.request.method} ${m.usage.request.path}`);
const cacheLine = (d: Decisions) => (d.deliverables.caching ? `${d.cacheTtl} minutes, in memory` : 'off');
const authLine = (m: Manifest, d: Decisions) => (d.deliverables.auth ? `${m.authMethods[0].label}, read from ${credentialFields(m.authMethods[0]).filter(f => !f.optional).map(f => envName(m, f.name)).join(', ')}` : 'left out. Pass a fetch that signs every request');
const retryLine = (d: Decisions) => (d.deliverables.errors ? `${d.retries}, exponential backoff` : 'off. One try per request');
const logLine = (d: Decisions) => (d.deliverables.logging ? d.logLevel : 'off');
const pagingLine = (m: Manifest, d: Decisions) => (d.deliverables.pagination ? m.users.pagination.type : 'off. First page only');

const readme = (m: Manifest, hash: string, d: Decisions, pack: AppPack, passed: number) => `# ${m.app.name} integration

Generated by Integration Builder from manifest ${hash}. Read only, one host.

${d.deliverables.client ? '' : `This is the manifest only. Build your own client from manifest.json; the sandbox checks ran against the reference connector.\n\n`}${passed} sandbox scenarios passed against a simulated ${m.app.name} built from its docs. The live API was not called, so run one read-only check with a real credential before you rely on this.

## Decisions

- Auth: ${authLine(m, d)}
- Users: ${d.deliverables.users ? `${m.users.request.method} ${m.users.request.path}` : 'not exported'}
- Usage: ${usageLine(m)}
${(m.usage.kind === 'event_log' || m.usage.kind === 'aggregate_report') && m.usage.window ? `- Usage window: ${d.window} days\n` : ''}- Pagination: ${pagingLine(m, d)}
- Retries: ${retryLine(d)}
- Log level: ${logLine(d)}
- Cache: ${cacheLine(d)}

## Data access

${pack.endpoints.map(e => `- ${isAllowed(e, d.access) ? 'Allowed' : 'Blocked'}: ${e.path} (${e.sensitivity})`).join('\n')}

## Files

${d.deliverables.client ? '' : 'Only manifest.json. '}Keep manifest.json next to ${m.app.slug}.connector.ts. runtime.ts and manifest.ts are the trusted runtime. manifest.ts needs zod.
`;

export const buildFiles = (pack: AppPack, d: Decisions, sources: { runtime: string; manifest: string }, passed: number): BundleFile[] => {
  const m = applyDecisions(pack.manifest, d);
  const hash = hashManifest(m);
  const all = bundleFrom(m, hash, sources, connectorSettings(d, pack.endpoints));
  const files = d.deliverables.client ? all : { 'manifest.json': all['manifest.json'] };
  return [...Object.entries(files), ['README.md', readme(m, hash, d, pack, passed)]].map(([name, code]) => ({ name, code }));
};

/** Null when there is no client to call. */
export const usageSnippet = (m: Manifest, d: Decisions, from: string) => {
  if (!d.deliverables.client) return null;
  const name = m.app.slug.replace(/(^|-)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase());
  const credentials = credentialFields(m.authMethods[0]).filter(f => !f.optional).map(f => `    ${f.name}: process.env.${envName(m, f.name)}!,`);
  const auth = d.deliverables.auth ? `  credentials: {\n${credentials.join('\n')}\n  },` : '  credentials: {},\n  fetch: yourSignedFetch,';
  const connection = m.connectionFields.length ? `\n  connection: { ${m.connectionFields.map(f => `${f.name}: '${f.example}'`).join(', ')} },` : '';
  const [fn, out, log] = d.deliverables.users ? [`get${name}Users`, '{ users, complete }', 'users.length, complete'] : [`get${name}Usage`, '{ usage, status }', 'usage.length, status'];
  return `import { ${fn} } from "${from}";

const ${out} = await ${fn}({
${auth}${connection}
});

console.log(${log});`;
};

export const buildPrompt = (pack: AppPack, d: Decisions, files: BundleFile[], passed: number) => {
  const m = applyDecisions(pack.manifest, d);
  const allowed = pack.endpoints.filter(e => isAllowed(e, d.access));
  const blocked = pack.endpoints.filter(e => !isAllowed(e, d.access));
  const host = m.baseUrl.replace(/^https:\/\//, '').split('/')[0];
  return `Add a read-only ${m.app.name} integration to this repo.

Context
- Generated by Integration Builder from ${m.app.name}'s docs. ${passed} sandbox scenarios passed against a simulated ${m.app.name}. The live API has not been called.
- The attached files go in ${FOLDER(m)}: ${files.map(f => f.name).join(', ')}.
- Use them as they are. Don't rewrite them.

Decisions already made (ask me before changing any)
- Client: ${d.deliverables.client ? 'generated, in the attached files' : 'not generated. Write a client from manifest.json'}.
- Auth: ${authLine(m, d)}.
- Users: ${d.deliverables.users ? `${m.users.request.method} ${m.users.request.path}` : 'not exported'}.
- Usage: ${usageLine(m)}.
- Pagination: ${pagingLine(m, d)}.
- Errors: classified by the runtime. Retries ${retryLine(d)}.${d.deliverables.errors ? ' On 429, follow Retry-After.' : ''}
- Logging: ${d.deliverables.logging ? `JSON at ${d.logLevel}. Never log secrets` : 'off'}.
- Caching: ${cacheLine(d)}.

Your task
1. Copy the files into ${FOLDER(m)}.
2. Add the credentials above to .env.example and to our secrets config. Never hard-code them.
3. Call the generated functions from the place where our other integrations are scheduled.
4. Run one read-only check with a real credential and tell me the result.

Guardrails
- Only ${host}, only these paths: ${allowed.map(e => e.path).join(', ')}.
- Never call: ${blocked.map(e => e.path).join(', ') || 'nothing blocked'}.
- Reads only. POST only where the manifest states why it is read-only.
- Never print or store unmasked names or emails outside production.
- zod is the only dependency. Don't add others.
- If anything conflicts with the decisions above, stop and ask.`;
};

/** Plain words for a ticket or a chat message to whoever sets it up. */
export const buildSummary = (pack: AppPack, d: Decisions, passed: number) => {
  const m = applyDecisions(pack.manifest, d);
  const name = m.app.name;
  const usage = m.usage.kind === 'unavailable' ? null : m.usage.kind === 'last_activity_field' ? 'when each person was last active'
    : `${m.usage.kind === 'event_log' ? 'who did what and when' : 'a usage report'}${m.usage.window ? `, over the last ${d.window} days` : ''}`;
  const reads = [d.deliverables.users ? `everyone in our ${name} account and their role` : null, usage].filter(r => r !== null);
  const blocked = pack.endpoints.filter(e => !isAllowed(e, d.access));
  return `${name} integration, ready to set up

- Reads: ${reads.join(', and ') || 'nothing yet'}. Read only.
- Blocked: ${blocked.map(e => `${e.name} (${e.path})`).join(', ') || 'nothing'}.
- Checks: ${passed} passed against a simulated ${name} built from its docs. Nothing touched our real account.
- Still needed: one read-only check with a real ${name} credential before we rely on it.

The generated files and a prompt for an AI coding tool are ready in Integration Builder.`;
};
